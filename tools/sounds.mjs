// Writes app/data/sounds.js: the pronunciation of every word the app's texts use (the
// readings, the Speed Studies drills and writing, the Writing Practice, the sentences, and the
// words of the examples), from the CMU Pronouncing Dictionary, for js/bysound.js.
//
//   node tools/sounds.mjs path/to/cmudict.dict
//
// The dictionary: https://github.com/cmusphinx/cmudict (BSD 2-clause licence, Carnegie Mellon
// University). Only the words the app needs are kept, with their first pronunciation.
import fs from 'node:fs';
import { READINGS } from '../app/data/reading.js';
import { SPEED } from '../app/data/speed.js';
import { EXAMPLES } from '../app/data/examples.js';
import { paragraphLines } from '../app/js/manualtext.js';

const WRITING_PRACTICE = [33, 64, 90, 111, 132, 152, 173, 191, 208, 226, 237, 248];

const dictPath = process.argv[2];
if (!dictPath) throw new Error('usage: node tools/sounds.mjs path/to/cmudict.dict');
const dict = new Map();
// Words the app's texts use that the dictionary lacks (caret: the Unit 2 Speed Studies drill).
const SUPPLEMENT = { caret: 'K AE1 R AH0 T' };
for (const line of fs.readFileSync(dictPath, 'utf8').split('\n')) {
  const m = /^([a-z']+) ([A-Z0-9 ]+?)(?: #.*)?$/.exec(line.trim());
  if (m && !dict.has(m[1])) dict.set(m[1], m[2]);
}

const texts = [
  ...READINGS.flatMap((r) => r.passages.flatMap((p) => p.text)),
  ...SPEED.flatMap((x) => [...x.figures.flatMap((f) => f.key ?? []), ...(x.writing ? x.text : [])]),
  ...WRITING_PRACTICE.flatMap((n) => paragraphLines(n)),
  ...EXAMPLES.map((e) => e.title),
];
const words = new Set(texts.flatMap((t) => t.toLowerCase().match(/[a-z]+/g) ?? []));
// The bases the endings are taken from (wordhelp.js): going → go, taking → take, etc.
for (const w of [...words]) {
  for (const [suffix, add] of [['ings', ['']], ['ing', ['', 'e']], ['ies', ['y']], ['es', ['', 'e']], ['s', ['']], ['ied', ['y']], ['ed', ['', 'e']], ['d', ['']], ['ly', ['', 'le']]]) {
    if (!w.endsWith(suffix)) continue;
    const b = w.slice(0, -suffix.length);
    for (const a of add) words.add(b + a);
    if (b.length > 2 && b.at(-1) === b.at(-2)) words.add(b.slice(0, -1));
  }
}
for (const [w, p] of Object.entries(SUPPLEMENT)) if (!dict.has(w)) dict.set(w, p);
const kept = [...words].filter((w) => dict.has(w)).sort();
const body = kept.map((w) => `  ${/^[a-z]+$/.test(w) ? w : JSON.stringify(w)}: '${dict.get(w)}',`).join('\n');
fs.writeFileSync(new URL('../app/data/sounds.js', import.meta.url), `// Pronunciations, from the CMU Pronouncing Dictionary (BSD 2-clause licence, Carnegie Mellon
// University; https://github.com/cmusphinx/cmudict), for js/bysound.js: only the words the
// app's texts use. Generated by tools/sounds.mjs; do not edit.
export const SOUNDS = {
${body}
};
`);
console.log(`${kept.length} of ${words.size} words`);
