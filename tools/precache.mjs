// Writes app/precache.js: every file the app needs, for the service worker (app/sw.js) to
// save on install, so the app works offline (e.g. from an iPad's Home Screen).
//
//   node tools/precache.mjs           write the list
//   node tools/precache.mjs --check   exit 1 if the list is out of date (CI)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../app/', import.meta.url));
const OUT = join(ROOT, 'precache.js');
const SKIP = new Set(['sw.js', 'precache.js']); // the worker and its list are not cached by it

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    if (d.name.startsWith('.')) return [];
    const p = join(dir, d.name);
    return d.isDirectory() ? walk(p) : [relative(ROOT, p).split(sep).join('/')];
  });
}

export function precacheList() {
  return ['./', ...walk(ROOT).filter((f) => !SKIP.has(f)).sort()];
}

export function precacheSource(list = precacheList()) {
  return `// Generated by tools/precache.mjs (npm run precache). Do not edit.\nself.PRECACHE = [\n${list.map((f) => `  '${f}',`).join('\n')}\n];\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = precacheSource();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur !== src) {
      console.error('app/precache.js is out of date: run npm run precache');
      process.exit(1);
    }
    console.log('app/precache.js is up to date');
  } else {
    writeFileSync(OUT, src);
    console.log(`wrote ${relative(process.cwd(), OUT)} (${precacheList().length} files)`);
  }
}
