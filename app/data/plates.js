  'p8-kr-gl': { page: 8, caption: 'The kr and gl combinations' },
  'p9-gr-kl': { page: 9, caption: 'gr is written like longhand y; kl like longhand h' },
  'p42-th': { page: 42, caption: 'Unit 9: which th to use in a word' },
